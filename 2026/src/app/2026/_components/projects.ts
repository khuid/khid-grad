// 한글뿐인 제목은 폴더 이름을 따로 정함 (소개글의 본인 영문 표기, 없으면 로마자 표기)
const SLUG_OF: Record<string, string> = { 이상유희: "isang-yuhee", 이음마루: "ieummaru" };

// 제목 → 폴더 이름 (영문·숫자만, 나머지는 -)
const slug = (title: string) => SLUG_OF[title] ?? title.replace(/[^A-Za-z0-9]+/g, "-").replace(/^-|-$/g, "").toLowerCase();

function filesOf(cls: ClassKey, title: string): Pick<Project, "thumb" | "media"> {
  const key = `${cls}/${slug(title)}`;
  const list = FILES[key];
  if (!list) return { media: [] };
  const dir = `/2026/projects/${key}`;
  return {
    thumb: `${dir}/thumb.webp`,
    media: list.map((f): Media => (f.endsWith(".mp4") ? { type: "video", src: `${dir}/${f}` } : { type: "image", src: `${dir}/${f}.webp` })),
  };
}

// 작품 제목 가나다 → abc → 숫자·기호 순 (앞의 기호·공백은 무시, 대소문자 구분 없음)
function group(title: string) {
  const ch = title.replace(/^[^\p{L}\p{N}]+/u, "")[0] ?? "";
  if (/\p{Script=Hangul}/u.test(ch)) return 0;
  if (/[a-z]/i.test(ch)) return 1;
  return 2;
}
export function byTitle(a: { title: string }, b: { title: string }) {
  return (
    group(a.title) - group(b.title) ||
    a.title.localeCompare(b.title, "ko", { sensitivity: "base", ignorePunctuation: true, numeric: true })
  );
}

// 아직 안 낸 작품(썸네일 없음)과 빈 자리 카드를 숨김 (2026-11-07 사용자 요청, 추가 제출이 들어오면 자동으로 보임). false면 다시 다 보임
const HIDE_EMPTY = true;

// 장표가 한 장면으로 이어지는 작품: 원본 이미지 경계 여백이 0px라 겹치면 선이 어긋남 → 이 작품만 겹치지 않음 (사용자 2026-11-07)
const SEAMLESS = new Set(["ai/nuun"]);

// 수상작 (2026-11 수상자 명단, 사용자). "수업키/작품 slug" → 상 이름.
// 수업 목록에서 수상작을 맨 앞으로: 대상 > 최우수상 > 우수상 > 예술디자인연구원장상(특별상이라 마지막), 같은 상끼리는 제목 순.
// 작품 상세의 수업명 줄 오른쪽 끝에 상 이름을 포인트핑크로 표기
export const AWARD_ORDER = ["대상", "최우수상", "우수상", "예술디자인연구원장상"] as const;
export type Award = (typeof AWARD_ORDER)[number];
const AWARDS: Record<string, Award> = {};
const awardRank = (w: { award?: Award }) => (w.award ? AWARD_ORDER.indexOf(w.award) : AWARD_ORDER.length);

// 번호(주소 /<수업>/<번호>)는 정렬한 순서대로 (수상작이 맨 앞), 빈 자리는 맨 뒤 (숨긴 카드는 번호에서도 빠짐)
export const PROJECTS: Project[] = CLASSES.flatMap((c) => {
  // 만든 사람도 가나다 순
  const filled = WORKS[c.key]
    .map(([title, members, description]) => ({ title, members: [...members].sort((a, b) => a.localeCompare(b, "ko")), description }))
    .sort(byTitle);
  const empty = Array.from({ length: Math.max(0, SLOTS[c.key] - filled.length) }, () => ({ title: "작품 제목", members: [] }));
  return [...filled, ...empty]
    .map((w) => ({
      ...w,
      links: (LINKS[`${c.key}/${slug(w.title)}`] ?? []).map(([label, href]) => ({ label, href })),
      ...filesOf(c.key, w.title),
      seamless: SEAMLESS.has(`${c.key}/${slug(w.title)}`),
      award: w.members.length ? AWARDS[`${c.key}/${slug(w.title)}`] : undefined,
    }))
    .sort((a, b) => awardRank(a) - awardRank(b)) // 안정 정렬이라 같은 상·수상 없는 작품끼리는 원래(제목) 순서 유지
    .filter((w) => !HIDE_EMPTY || w.thumb)
    .map((w, i) => ({ cls: c.key, no: String(i + 1).padStart(2, "0"), ...w }));
});

export const classOf = (key: string) => CLASSES.find((c) => c.key === key);
export const projectsOf = (key: ClassKey) => PROJECTS.filter((p) => p.cls === key);
export const projectHref = (p: Project) => `/2026/projects/${p.cls}/${p.no}`;
export const worksOf = (name: string) => PROJECTS.filter((p) => p.members.includes(name)).sort(byTitle);
